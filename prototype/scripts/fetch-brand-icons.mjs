/* One-time asset import. Run only when intentionally refreshing the store shortlist. */
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import vm from 'node:vm';

const root = fileURLToPath(new URL('../dist/', import.meta.url));
const source = readFileSync(join(root, 'discover-brands.js'), 'utf8');
const context = {window: {}};
vm.runInNewContext(source, context);
const brands = context.window.DiscoverBrands;
const directory = join(root, 'assets', 'brand-icons');
mkdirSync(directory, {recursive: true});

const extensions = {'image/png': 'png', 'image/jpeg': 'jpg', 'image/webp': 'webp', 'image/x-icon': 'ico', 'image/vnd.microsoft.icon': 'ico', 'image/svg+xml': 'svg'};
const results = [];
let next = 0;
async function worker() {
  while (next < brands.length) {
    const brand = brands[next++];
    const host = new URL(brand.url).hostname;
    const service = `https://www.google.com/s2/favicons?domain=${encodeURIComponent(host)}&sz=128`;
    try {
      const response = await fetch(service, {signal: AbortSignal.timeout(15000)});
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      const mime = (response.headers.get('content-type') || '').split(';')[0].toLowerCase();
      const extension = extensions[mime];
      if (!extension) throw new Error(`Unsupported image type: ${mime}`);
      const bytes = Buffer.from(await response.arrayBuffer());
      if (!bytes.length || bytes.length > 200_000) throw new Error('Unexpected image size');
      const filename = `${brand.id}.${extension}`;
      writeFileSync(join(directory, filename), bytes);
      results.push({id: brand.id, name: brand.name, file: `assets/brand-icons/${filename}`, site: brand.url, iconSource: response.headers.get('content-location') || service, sha256: createHash('sha256').update(bytes).digest('hex')});
      process.stdout.write(`✓ ${brand.id} ${brand.name}\n`);
    } catch (error) {
      results.push({id: brand.id, name: brand.name, file: null, site: brand.url, error: error.message});
      process.stdout.write(`! ${brand.id} ${brand.name}: ${error.message}\n`);
    }
  }
}
await Promise.all(Array.from({length: 5}, worker));
results.sort((a, b) => a.id - b.id);
writeFileSync(join(directory, 'sources.json'), JSON.stringify(results, null, 2) + '\n');
writeFileSync(join(root, 'brand-icon-map.js'), `/* Generated by scripts/fetch-brand-icons.mjs. */\nwindow.BrandIconMap = ${JSON.stringify(Object.fromEntries(results.filter((result) => result.file).map((result) => [result.id, result.file])))};\n`);
process.stdout.write(`${results.filter((result) => result.file).length}/${brands.length} icons saved\n`);
